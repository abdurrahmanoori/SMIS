import 'package:powersync/powersync.dart';

const _trackTimestamp = TrackPreviousValuesOptions(
  columnFilter: ['last_modified_utc'],
);

/// Only entities that currently exist in the Flutter application are included.
/// Adding a .NET entity does not automatically make it part of offline sync.
const appPowerSyncSchema = Schema([
  Table('language', [
    Column.text('name'),
    Column.text('code'),
    Column.integer('is_active'),
    Column.text('last_modified_utc'),
  ]),
  Table('app_user', [
    Column.text('language_id'),
    Column.text('last_modified_utc'),
  ]),
  Table('shop', [
    Column.text('name'),
    Column.text('shop_type'),
    Column.text('address'),
    Column.text('phone_number'),
    Column.text('email'),
    Column.text('tax_number'),
    Column.integer('is_active'),
    Column.text('last_modified_utc'),
  ], trackPreviousValues: _trackTimestamp),
  Table('category', [
    Column.text('name'),
    Column.text('code'),
    Column.text('description'),
    Column.integer('is_active'),
    Column.text('shop_id'),
    Column.text('last_modified_utc'),
  ], trackPreviousValues: _trackTimestamp),
  Table('unit_of_measure', [
    Column.text('name'),
    Column.text('symbol'),
    Column.text('description'),
    Column.text('last_modified_utc'),
  ], trackPreviousValues: _trackTimestamp),
  Table('product', [
    Column.text('name'),
    Column.text('base_unit_id'),
    Column.text('sku'),
    Column.text('description'),
    Column.integer('is_active'),
    Column.text('barcode'),
    Column.text('image_url'),
    Column.text('category_id'),
    Column.text('shop_id'),
    Column.real('reorder_point_base'),
    Column.real('reorder_quantity_base'),
    Column.text('last_modified_utc'),
  ], trackPreviousValues: _trackTimestamp),
  Table('product_unit', [
    Column.text('product_id'),
    Column.text('unit_of_measure_id'),
    Column.real('base_unit_quantity'),
    Column.text('last_modified_utc'),
  ], trackPreviousValues: _trackTimestamp),
  Table('product_price', [
    Column.text('product_unit_id'),
    Column.integer('sell_price'),
    Column.text('effective_date'),
    Column.text('end_date'),
    Column.text('last_modified_utc'),
  ], trackPreviousValues: _trackTimestamp),
  Table('supplier', [
    Column.text('shop_id'),
    Column.text('name'),
    Column.text('phone_number'),
    Column.text('notes'),
    Column.integer('is_active'),
    Column.text('last_modified_utc'),
  ], trackPreviousValues: _trackTimestamp),
  Table('purchase_order', [
    Column.text('shop_id'),
    Column.text('supplier_id'),
    Column.text('reference_number'),
    Column.text('ordered_at_utc'),
    Column.text('status'),
    Column.text('notes'),
    Column.text('last_modified_utc'),
  ]),
  Table('purchase_order_line', [
    Column.text('purchase_order_id'),
    Column.text('product_id'),
    Column.text('product_unit_id'),
    Column.real('ordered_quantity_entered'),
    Column.real('received_quantity_entered'),
    Column.real('returned_quantity_entered'),
    Column.integer('unit_cost_base'),
    Column.text('last_modified_utc'),
  ]),
  // Financial records are server-authoritative. PowerSync downloads confirmed
  // values only; payment commands are uploaded through a local outbox.
  Table('supplier_payable', [
    Column.text('shop_id'),
    Column.text('supplier_id'),
    Column.text('purchase_order_id'),
    Column.integer('total_amount'),
    Column.integer('credit_amount'),
    Column.text('last_modified_utc'),
  ]),
  Table('supplier_payable_entry', [
    Column.text('shop_id'),
    Column.text('supplier_payable_id'),
    Column.text('operation_id'),
    Column.text('kind'),
    Column.integer('amount'),
    Column.text('occurred_at_utc'),
    Column.text('last_modified_utc'),
  ]),
  Table('supplier_payment', [
    Column.text('shop_id'),
    Column.text('supplier_id'),
    Column.integer('amount'),
    Column.text('paid_at_utc'),
    Column.text('payment_method'),
    Column.text('reference_number'),
    Column.text('notes'),
    Column.text('last_modified_utc'),
  ]),
  Table('supplier_payment_allocation', [
    Column.text('shop_id'),
    Column.text('supplier_payment_id'),
    Column.text('supplier_payable_id'),
    Column.integer('amount'),
    Column.text('last_modified_utc'),
  ]),
  Table.localOnly('sync_error', [
    Column.text('table_name'),
    Column.text('record_id'),
    Column.text('operation'),
    Column.text('message'),
    Column.text('details'),
    Column.text('created_at_utc'),
  ]),
  Table.localOnly('stock_cache', [
    Column.text('payload'),
    Column.text('cached_at_utc'),
  ]),
  Table.localOnly('stock_outbox', [
    Column.text('kind'),
    Column.text('payload'),
    Column.text('created_at_utc'),
    Column.text('state'),
    Column.text('error'),
  ]),
  Table.localOnly('purchase_order_outbox', [
    Column.text('aggregate_id'),
    Column.text('kind'),
    Column.text('payload'),
    Column.text('created_at_utc'),
    Column.text('state'),
    Column.text('error'),
  ]),
  Table.localOnly('supplier_finance_outbox', [
    Column.text('supplier_id'),
    Column.text('kind'),
    Column.text('payload'),
    Column.text('created_at_utc'),
    Column.text('state'),
    Column.text('error'),
  ]),
]);
